#!/usr/bin/env python3
"""Generate DevonCraft's pig/cow pixel atlas and compact RGB565 index header.

The 64x32 atlas has four columns by two rows of 16x16 tiles. The compact
header stores one hexadecimal palette index per pixel; mob_renderer.cpp expands
it into the calculator's RGB565 texture format once, on first use.
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
PNG = ROOT / "textures" / "animals.png"
HEADER = ROOT / "textures" / "animals.h"

# Fixed 16-colour palette: 0-9 are pig materials, 10-15 cow materials.
PALETTE = [
    (46, 34, 31),    # 0 dark eye/nostril
    (86, 59, 48),    # 1 dark brown
    (125, 82, 57),   # 2 warm brown
    (165, 83, 100),  # 3 deep rose
    (196, 106, 120), # 4 shaded pig pink
    (226, 139, 148), # 5 pig pink
    (242, 168, 172), # 6 pig highlight
    (249, 190, 187), # 7 snout highlight
    (36, 32, 32),    # 8 eye black
    (75, 54, 47),    # 9 hoof
    (208, 204, 188), # 10 cow shadow ivory
    (233, 228, 211), # 11 cow ivory
    (249, 245, 228), # 12 cow highlight
    (108, 71, 49),   # 13 cow dark patch
    (128, 83, 56),   # 14 cow warm patch
    (222, 180, 165), # 15 cow muzzle
]
image = Image.new("P", (64, 32), 0)
flat_palette = []
for colour in PALETTE:
    flat_palette.extend(colour)
flat_palette.extend([0] * (768 - len(flat_palette)))
image.putpalette(flat_palette)


def tile(index, painter):
    cell = Image.new("P", (16, 16), 0)
    cell.putpalette(flat_palette)
    painter(ImageDraw.Draw(cell))
    image.paste(cell, ((index % 4) * 16, (index // 4) * 16))


def fleck(base, light, shadow, count=24):
    def paint(d):
        d.rectangle((0, 0, 15, 15), fill=base)
        # A fixed grid pattern makes the texture stable and legible at scale.
        for y in range(2, 15, 4):
            for x in range((y // 4) % 2, 16, 5):
                d.point((x, y), fill=light if (x + y) % 2 else shadow)
        d.line((1, 1, 14, 1), fill=light)
        d.point((1, 2), fill=light)
    return paint

# Pig skin, snout, inner ear, eye and hoof.
tile(0, fleck(5, 6, 4))

def pig_muzzle(d):
    d.rectangle((0, 0, 15, 15), fill=5)
    d.rectangle((1, 2, 14, 13), fill=7)
    d.rectangle((3, 4, 12, 11), fill=6)
    d.rectangle((4, 6, 6, 9), fill=1)
    d.rectangle((10, 6, 12, 9), fill=1)
    d.point((2, 3), fill=12)
    d.point((13, 3), fill=12)
tile(1, pig_muzzle)

def inner_ear(d):
    d.rectangle((0, 0, 15, 15), fill=5)
    d.polygon([(2, 14), (4, 3), (8, 1), (12, 4), (14, 14)], fill=3)
    d.polygon([(5, 11), (6, 5), (9, 4), (11, 11)], fill=6)
tile(2, inner_ear)

def pig_eye(d):
    d.rectangle((0, 0, 15, 15), fill=5)
    d.rectangle((5, 5, 10, 10), fill=1)
    d.rectangle((6, 5, 8, 8), fill=8)
    d.point((6, 6), fill=12)
tile(3, pig_eye)
tile(4, fleck(9, 2, 1))

# Cow ivory coat and irregular chestnut patches.
tile(5, fleck(11, 12, 10))

def cow_spots(d):
    d.rectangle((0, 0, 15, 15), fill=11)
    d.polygon([(0, 2), (3, 0), (7, 1), (8, 5), (5, 8), (1, 7)], fill=13)
    d.polygon([(10, 0), (15, 0), (15, 5), (13, 7), (10, 5)], fill=14)
    d.polygon([(7, 10), (11, 8), (15, 10), (14, 15), (9, 15), (6, 13)], fill=13)
    d.point((4, 9), fill=10)
tile(6, cow_spots)

def cow_muzzle(d):
    d.rectangle((0, 0, 15, 15), fill=2)
    d.rectangle((2, 2, 13, 13), fill=15)
    d.rectangle((4, 6, 6, 9), fill=1)
    d.rectangle((10, 6, 12, 9), fill=1)
    d.line((3, 3, 12, 3), fill=12)
tile(7, cow_muzzle)

image.save(PNG, optimize=True)
indices = image.tobytes()
with HEADER.open("w", encoding="ascii") as f:
    f.write("// Generated by tools/gen_mob_textures.py from animals.png.\n")
    f.write("// Four columns x two rows of 16x16 tiles; each hex digit is a palette index.\n")
    f.write("static const char mob_animals_indices[] =\n")
    for i in range(0, len(indices), 64):
        f.write('    "' + ''.join(format(v, 'x') for v in indices[i:i+64]) + '"\n')
    f.write("    ;\n")
print("Generated", PNG, "and", HEADER)
